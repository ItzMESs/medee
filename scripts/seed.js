const cats = Object.fromEntries(db.prepare('SELECT id, slug FROM categories').all().map((c) => [c.slug, c.id]));
const author = db.prepare('SELECT id FROM users ORDER BY id LIMIT 1').get();
const uploads = path.join(__dirname, '..', 'uploads');
const ins = db.prepare(`INSERT INTO articles (title, slug, excerpt, content, image, category_id, author_id, status, is_featured, is_breaking, views, published_at)
  VALUES (?, ?, ?, ?, ?, ?, ?, 'published', ?, ?, ?, ?)`);

samples.forEach(([cat, title, excerpt, featured, breaking], i) => {
  const img = `demo-${i + 1}.jpg`;
  const content = `<p>${excerpt}</p><p>Энэ бол жишээ мэдээ. Админ панелаас засаж, устгаж эсвэл шинэ мэдээ нэмж болно.</p>` +
    '<h2>Дэлгэрэнгүй</h2><p>Холбогдох албан тушаалтнууд энэ асуудлаар дараагийн долоо хоногт нэмэлт мэдээлэл өгөхөө мэдэгдлээ.</p>' +
    '<blockquote>"Бид иргэдэд бодит, шуурхай мэдээллийг хүргэхийг зорьж байна."</blockquote>';
  ins.run(title, slugify(title), excerpt, content, fs.existsSync(path.join(uploads, img)) ? `/uploads/${img}` : null,
    cats[cat] || null, author.id, featured, breaking, Math.floor(Math.random() * 3000) + 50,
    toDb(new Date(Date.now() - i * 2.5 * 3600e3)));
});
